class TestValidator:

    def test_valid_python_passes(self):
        code = "def hello(name: str) -> str:\n    return f'Hello, {name}!'\n"
        result = validate(code, filename="hello.py")
        assert result.valid is True
        assert len(result.errors) == 0

    def test_invalid_python_blocked(self):
        code = "def broken(\n    print('oops')"
        result = validate(code, filename="broken.py")
        assert result.valid is False
        assert len(result.errors) > 0
        assert "SyntaxError" in result.errors[0]

    def test_non_python_file_skips_compile(self):
        code = "SELECT * FROM users WHERE id = ?;"
        result = validate(code, filename="query.sql")
        # No Python compile attempted — should pass
        assert result.valid is True

    def test_summary_for_valid(self):
        code = "x = 42\n"
        result = validate(code, filename="x.py")
        assert "passed" in result.summary()

    def test_summary_for_invalid(self):
        code = "def bad syntax:\n"
        result = validate(code, filename="bad.py")
        assert "failed" in result.summary().lower() or not result.valid
