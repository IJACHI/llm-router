# ---------------------------------------------------------------------------
# Humanizer tests
# ---------------------------------------------------------------------------

class TestHumanizer:

    def test_strips_certainly_opener(self):
        text = "Certainly! Here is how you do it:\n\nThe answer is 42."
        result = humanize(text)
        assert "Certainly" not in result
        assert "42" in result

    def test_strips_as_an_ai(self):
        text = "As an AI language model, I cannot provide personal opinions.\nBut here are the facts."
        result = humanize(text)
        assert "As an AI" not in result
        assert "facts" in result

    def test_strips_happy_to_help(self):
        text = "I'd be happy to help you with that!\nThe function is called `sort()`."
        result = humanize(text)
        assert "happy to help" not in result
        assert "sort()" in result

    def test_strips_closing_phrase(self):
        text = "The answer is Python.\n\nI hope this helps!"
        result = humanize(text)
        assert "I hope this helps" not in result

    def test_strips_feel_free_closer(self):
        text = "Use `os.path.join()`.\n\nFeel free to ask if you have more questions."
        result = humanize(text)
        assert "Feel free" not in result

    def test_em_dash_normalized(self):
        text = "This is great\u2014really great."
        result = humanize(text)
        assert "\u2014" not in result
        assert "-" in result

    def test_strips_ai_code_comments(self):
        code = "# Step 1: Initialize the router\nrouter = Router()\n# Here we build the result\nresult = router.route(prompt)"
        result = humanize(code)
        assert "Step 1:" not in result
        assert "router = Router()" in result

    def test_preserves_real_content(self):
        text = "Use `hashlib.sha256()` instead of MD5 for security reasons."
        result = humanize(text)
        assert "sha256" in result
        assert "MD5" in result

    def test_simplifies_in_order_to(self):
        text = "In order to start the server, run the command below."
        result = humanize(text)
        assert "In order to" not in result
        assert "to" in result

    def test_strips_attribution_watermark(self):
        code = "# Generated by Claude 3.7 Sonnet\ndef main():\n    pass"
        result = humanize(code)
        assert "Generated by" not in result
        assert "def main" in result

    def test_empty_string_safe(self):
        assert humanize("") == ""
        assert humanize("   ") == ""


