class TestSecurityScanner:

    def test_detects_eval(self):
        code = "result = eval(user_input)"
        report = scan(code)
        categories = {i.category for i in report.issues}
        assert "Code Injection" in categories

    def test_detects_hardcoded_secret(self):
        code = 'api_key = "sk-1234567890abcdef"'
        report = scan(code)
        categories = {i.category for i in report.issues}
        assert "Secrets Exposure" in categories

    def test_detects_md5(self):
        code = "digest = hashlib.md5(data).hexdigest()"
        report = scan(code)
        categories = {i.category for i in report.issues}
        assert "Weak Cryptography" in categories

    def test_auto_fixes_md5_to_sha256(self):
        code = "digest = hashlib.md5(data).hexdigest()"
        fixed, issues = scan_and_fix(code)
        assert "hashlib.sha256(" in fixed
        assert "hashlib.md5(" not in fixed

    def test_auto_fixes_yaml_unsafe_load(self):
        code = "data = yaml.load(stream)"
        fixed, issues = scan_and_fix(code)
        assert "yaml.safe_load" in fixed

    def test_auto_fixes_debug_true(self):
        code = "DEBUG = True"
        fixed, issues = scan_and_fix(code)
        assert "DEBUG = False" in fixed

    def test_detects_pickle_loads(self):
        code = "obj = pickle.loads(data)"
        report = scan(code)
        categories = {i.category for i in report.issues}
        assert "Unsafe Deserialization" in categories

    def test_detects_shell_injection(self):
        code = "subprocess.run(cmd, shell=True)"
        report = scan(code)
        categories = {i.category for i in report.issues}
        assert "Injection" in categories

    def test_clean_code_is_safe(self):
        code = "def add(a: int, b: int) -> int:\n    return a + b\n"
        report = scan(code)
        assert report.is_safe is True
        assert len(report.issues) == 0

    def test_format_summary_no_issues(self):
        code = "x = 1 + 2"
        report = scan(code)
        summary = format_security_summary(report)
        assert "No security vulnerabilities" in summary


